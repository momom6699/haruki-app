#!/usr/bin/env node
/**
 * 皇居周辺の地物を書き出す。
 *
 *   node scripts/make-area-map.mjs
 *
 * 出どころは `scripts/lib/kokyo.mjs` の座標——門・交差点・駅から起こした概形で、
 * OSM から取り出したものではない。実データが来たら
 *   node scripts/build-map-fixture.mjs <overpass.json>
 * が同じスキーマで上書きする。
 *
 * 出す種類は Android 版 OsmMap.kt が引くものと同じに揃える：
 * park（緑地）/ water（水面）/ river（水路の線）/ greenway（緑道）/ road（走れる幅の道）。
 * 店・POI・ラベル・道路番号は入れない（§4）。
 */
import { writeFileSync } from 'node:fs';
import { CENTER, INNER_MOAT_CHAIN, band, coord, ll, loopRing, rightNormals, toXY } from './lib/kokyo.mjs';

const features = [];

const line = (coords, kind) => features.push({
  type: 'Feature',
  properties: { kind },
  geometry: { type: 'LineString', coordinates: coords },
});
const area = (coords, kind) => {
  const ring = coords.slice();
  const [a, b] = [ring[0], ring[ring.length - 1]];
  if (a[0] !== b[0] || a[1] !== b[1]) ring.push(a);
  features.push({ type: 'Feature', properties: { kind }, geometry: { type: 'Polygon', coordinates: [ring] } });
};
/** 手で置いた少数の点から緯度経度の線を引く。[lat, lon] の並びで書けるようにする。 */
const path = (pairs) => pairs.map(([lat, lon]) => ll(lat, lon));

/* --- 内堀と皇居 ---------------------------------------------------------- */

const ring = loopRing();
const normals = rightNormals(ring);
const shift = (i, distance) => ({
  east: ring[i].east + normals[i].east * distance,
  north: ring[i].north + normals[i].north * distance,
});

// 濠の手前岸と奥岸。奥岸の内側がそのまま皇居の森になる。
const nearBank = ring.map((p, i) => shift(i, p.inset));
const farBank = ring.map((p, i) => shift(i, p.inset + p.width));

// 濠は門で土手に切られている。名前ごとにまとめて、区間ごとの帯として塗る。
let start = 0;
for (let i = 1; i <= ring.length; i++) {
  const here = ring[i % ring.length].moat;
  if (here === ring[start].moat && i < ring.length) continue;
  const slice = (arr) => arr.slice(start, i + 1).length > 1 ? arr.slice(start, Math.min(i + 1, arr.length)) : [];
  const near = slice(nearBank);
  const far = slice(farBank);
  if (near.length > 1) area([...near, ...far.slice().reverse()].map(coord), 'water');
  start = i;
}

// 濠の内側はぜんぶ緑——西は吹上御苑の森、東は皇居外苑の芝と黒松。
area(farBank.map(coord), 'park');
// その2つを分ける内側の濠（桔梗濠・蛤濠・二重橋濠）。
area(band(INNER_MOAT_CHAIN.map(([lat, lon]) => toXY(lat, lon)), 52).map(coord), 'water');

/* --- 内堀通りと、そこから伸びる幹線 --------------------------------------- */

// 走る歩道は濠側。地物としては通りの中心線をそのまま道に使う。
line([...ring.map(coord), coord(ring[0])], 'road');

